/**
 * scripts/ds-colors.js: customerapp's colour tokens, generated from
 * tailwind.config.js beside tappler-shared's palette.
 */
const {
  ONE_OFFS,
  generate,
  sharedPalette,
  tokens,
  main,
} = require("../ds-colors")
const { resolve } = require("../nw-resolve")

describe("ds:colors", () => {
  it("keeps src/styles/dsColors.ts what tailwind.config.js and ONE_OFFS make it", () => {
    const error = jest.spyOn(console, "error").mockImplementation(() => {})
    const code = main(["--check"])
    error.mockRestore()
    expect(code).toBe(0)
  })

  it("takes what shared's palette lacks, by name and value, and says where a name differs", () => {
    const list = tokens({
      tailwind: {
        theme: {
          extend: {
            colors: {
              red: "#CC0000", // shared has it: left out
              grey55: "#C6C6C6", // shared's grey55 is another colour: in
              homeInk: "#111111", // shared hasn't: in
            },
          },
        },
      },
      shared: { red: "#cc0000", grey55: "#00000091" },
    })
    // shared's name for another colour is never reused: `dsColors.grey55`
    // beside shared's `colors.grey55` (PickAddressScreen/styles.ts:16) was
    // two colours under one name (review-ca-w0's low)
    expect(list.slice(0, 2)).toEqual([
      {
        name: "grey55Class",
        value: "#C6C6C6",
        note: "the grey55 class's colour; shared's grey55 is #00000091",
      },
      { name: "homeInk", value: "#111111", note: null },
    ])
    expect(list.slice(2).map((t) => t.name)).toEqual(
      ONE_OFFS.map((o) => o.name)
    )
  })

  it("refuses a name that shadows one of shared's colours with another value", () => {
    const ONE = { tailwind: { theme: { extend: { colors: {} } } } }
    // a one-off under shared's name
    expect(() =>
      tokens({ ...ONE, shared: { redAlpha10: "#000000" } })
    ).toThrow(/redAlpha10 would shadow shared's redAlpha10 \(#000000\)/)
    // the renamed class colour taken by shared too
    expect(() =>
      tokens({
        tailwind: { theme: { extend: { colors: { grey55: "#C6C6C6" } } } },
        shared: { grey55: "#00000091", grey55Class: "#111111" },
      })
    ).toThrow(/grey55Class would shadow shared's grey55Class \(#111111\)/)
  })

  it("refuses a one-off named like a tailwind colour", () => {
    expect(() =>
      tokens({
        tailwind: { theme: { extend: { colors: { redAlpha10: "#000" } } } },
        shared: {},
      })
    ).toThrow(/one-off redAlpha10 is a tailwind colour too/)
  })

  it("names each one-off with what NativeWind draws for its class", () => {
    for (const o of ONE_OFFS.filter((x) => !x.from.startsWith("style "))) {
      const cls = o.from.split(",")[0]
      const style = resolve(cls).style
      expect({ cls, value: Object.values(style)[0] }).toEqual({
        cls,
        value: o.value,
      })
    }
  })

  it("names this app's own colours: the four shared lacks or draws otherwise, then the one-offs", () => {
    const list = tokens({
      tailwind: require("../../tailwind.config"),
      shared: sharedPalette(),
    })
    expect(list.map((t) => [t.name, t.value])).toEqual([
      ["red7", "#F76363"],
      ["grey55Class", "#C6C6C6"],
      ["blue1", "#4084F5"],
      ["blue2", "#4084F566"],
      ["redAlpha10", "rgba(204, 0, 0, 0.1)"],
      ["whiteAlpha20", "rgba(255, 255, 255, 0.2)"],
      ["whiteAlpha65", "rgba(255,255,255,0.65)"],
      ["whiteAlpha90", "rgba(255,255,255,0.9)"],
    ])
  })

  it("reads shared's palette from its source", () => {
    const shared = sharedPalette()
    expect(shared.red).toBe("#CC0000")
    expect(Object.keys(shared).length).toBeGreaterThan(50)
    expect(generate()).toMatch(/^\/\/ Generated by `yarn ds:colors`/)
  })
})
