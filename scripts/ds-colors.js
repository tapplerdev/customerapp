#!/usr/bin/env node
/**
 * yarn ds:colors [--check]
 *
 * Writes src/styles/dsColors.ts, customerapp's own colour tokens, so a StyleSheet
 * the design-system codemod writes can name every colour a class drew
 * instead of spelling it out (the ratchet lets colour literals only fall).
 *
 * Two parts:
 * - every colour in tailwind.config.js's theme.extend.colors that
 *   tappler-shared's palette (src/styles/colors.ts) doesn't have under the
 *   same name and value: red7, blue1, blue2 and grey55 (#C6C6C6 here,
 *   #00000091 in shared). Generated, so a value can't drift from the class
 *   that draws it;
 * - ONE_OFFS below: what the app's classes draw that no colour names, an
 *   opacity modifier on one (bg-red/10) or an arbitrary value, and colours
 *   of a DmText style the codemod writes again. Their names are provisional
 *   until Omar names them; renaming one is a one-line change here and a
 *   re-run.
 *
 * --check: exit 1 when the file isn't what this would write (a test runs it).
 */
const fs = require("fs")
const path = require("path")

const ROOT = path.resolve(__dirname, "..")
const OUT = path.join(ROOT, "src", "styles", "dsColors.ts")
const SHARED_PALETTE = path.join(
  ROOT,
  "..",
  "tappler-shared",
  "src",
  "styles",
  "colors.ts"
)

// name, the value NativeWind draws for the class, and where it is used.
// customerapp's classes draw two colours no colour names (proapp had its
// own six, none of which this app draws).
const ONE_OFFS = [
  {
    name: "redAlpha10",
    value: "rgba(204, 0, 0, 0.1)",
    from: "bg-red/10, CalendarTimePicker",
  },
  {
    name: "whiteAlpha20",
    value: "rgba(255, 255, 255, 0.2)",
    from: "bg-white/20, ImageViewerModal",
  },
]

/** The shared palette's entries, read from its source (`key: "value",`). */
const sharedPalette = (file = SHARED_PALETTE) => {
  const out = {}
  const source = fs.readFileSync(file, "utf8")
  for (const m of source.matchAll(/^\s*([A-Za-z_$][\w$]*)\s*:\s*"([^"]+)"/gm))
    out[m[1]] = m[2]
  return out
}

const same = (a, b) => String(a).toLowerCase() === String(b).toLowerCase()

/** [{ name, value, note }] in tailwind's order, then the one-offs. */
const tokens = ({ tailwind, shared }) => {
  const own = Object.entries(tailwind.theme.extend.colors)
    .filter(([name, value]) => typeof value === "string")
    .filter(([name, value]) => !(name in shared && same(shared[name], value)))
    .map(([name, value]) => ({
      name,
      value,
      note:
        name in shared
          ? `shared's ${name} is ${shared[name]}; customerapp's classes draw this`
          : null,
    }))
  const taken = new Set(own.map((t) => t.name))
  for (const o of ONE_OFFS)
    if (taken.has(o.name))
      throw new Error(`ds-colors: one-off ${o.name} is a tailwind colour too`)
  return [...own, ...ONE_OFFS.map((o) => ({ ...o, note: o.from }))]
}

const render = (list) => {
  const line = (t) =>
    `  ${t.name}: ${JSON.stringify(t.value)},${t.note ? ` // ${t.note}` : ""}`
  const oneOff = new Set(ONE_OFFS.map((o) => o.name))
  return [
    "// Generated by `yarn ds:colors` (scripts/ds-colors.js). Don't edit by hand:",
    "// change tailwind.config.js or the script's ONE_OFFS, and run it again.",
    "//",
    "// customerapp's own colour tokens: what tailwind.config.js names that",
    "// tappler-shared's palette (@tappler/shared/src/styles/colors) doesn't, then",
    "// colours the app's classes draw that nothing names (provisional names).",
    "export default {",
    ...list.filter((t) => !oneOff.has(t.name)).map(line),
    "  // Drawn by a class or a DmText style, named by nothing yet: provisional names.",
    ...list.filter((t) => oneOff.has(t.name)).map(line),
    "}",
    "",
  ].join("\n")
}

const generate = () => {
  // eslint-disable-next-line import/no-dynamic-require
  const tailwind = require(path.join(ROOT, "tailwind.config.js"))
  return render(tokens({ tailwind, shared: sharedPalette() }))
}

const main = (argv) => {
  const check = argv.includes("--check")
  const unknown = argv.filter((a) => a !== "--check")
  if (unknown.length) {
    console.error(
      `ds-colors: unknown argument ${unknown[0]}\nusage: yarn ds:colors [--check]`
    )
    return 2
  }
  const next = generate()
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : null
  if (check) {
    if (now === next) return 0
    console.error(
      `ds-colors: ${path.relative(ROOT, OUT)} is out of date; run yarn ds:colors`
    )
    return 1
  }
  if (now !== next) {
    fs.mkdirSync(path.dirname(OUT), { recursive: true })
    fs.writeFileSync(OUT, next)
  }
  console.log(`ds-colors: wrote ${path.relative(ROOT, OUT)}`)
  return 0
}

module.exports = { ONE_OFFS, OUT, generate, sharedPalette, tokens, main }

if (require.main === module) process.exitCode = main(process.argv.slice(2))
